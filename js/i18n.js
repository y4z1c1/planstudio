export let lang = 'tr';
try { lang = localStorage.getItem('ps:lang') || 'tr'; } catch {}
if (!STRINGS[lang]) lang = 'tr';

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', v);
  return s;
}

export function setLang(l) {
  try { localStorage.setItem('ps:lang', l); } catch {}
  location.reload();
}

// translate all elements carrying data-i18n / data-i18n-ph attributes
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
}
